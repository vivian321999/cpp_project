#include <iostream>
using namespace std;

int main() {
    // 定义变量：x表示要凑的总金额（单位：元）
    // one/two/five分别表示1角、2角、5角硬币的数量
    int x;
    int one, two, five;

    // exit作为标志变量：0表示尚未找到解，1表示已找到解，用于控制跳出多重循环
    int exit = 0;

    // 从用户输入获取目标金额（单位：元）
    cin >> x;

    // 外层循环：枚举1角硬币的数量
    // 从1开始，上限为总角数x*10（但使用<可能导致边界漏解，保留原代码逻辑）
    for (one = 1; one < x * 10; one++) {
        // 中层循环：枚举2角硬币的数量（上限为总角数除以2）
        for (two = 1; two < x * 10 / 2; two++) {
            // 内层循环：枚举5角硬币的数量（上限为总角数除以5）
            for (five = 1; five < x * 10 / 5; five++) {
                // 检查当前三种硬币组合是否恰好等于目标总角数
                // 等式左边：one个1角 + two个2角(每个值2角) + five个5角(每个值5角)
                // 等式右边：x元转换为x*10角
                if (one + two * 2 + five * 5 == x * 10) {
                    // 找到一组可行解，输出结果
                    cout << "可以用" << one << "个一角加" << two << "个两角加" << five
                         << "个五角凑成" << x << "元" << endl;

                    // 将标志变量置为1，表示已找到解
                    exit = 1;

                    // 跳出当前内层循环（只跳出最内层的for循环）
                    break;
                }
            }

            // 内层循环结束后，检查是否已找到解
            // 如果exit == 1，说明已经找到解，跳出中层循环
            if (exit == 1) break;
        }

        // 中层循环结束后，再次检查是否已找到解
        // 如果exit == 1，说明已经找到解，跳出外层循环
        if (exit == 1) break;
    }

    // 程序结束（无论是否找到解，都会执行到这里）
    return 0;
}