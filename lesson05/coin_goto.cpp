#include <iostream>
using namespace std;

int main() {
    // 定义变量：x表示要凑的总金额（单位：元），one/two/five分别表示1角、2角、5角硬币的数量
    int x;
    int one, two, five;

    // 从用户输入获取目标金额（单位：元）
    cin >> x;

    // 外层循环：枚举1角硬币的数量（从1开始，上限为 x*10 角，因为总金额为 x 元 = x*10 角）
    // 注意：这里用 one < x*10 而不是 <=，因为至少需要其他硬币参与，但严格说边界条件可优化
    for (one = 1; one < x * 10; one++) {
        // 中层循环：枚举2角硬币的数量（上限为总角数除以2，因为每个2角硬币占2角）
        for (two = 1; two < x * 10 / 2; two++) {
            // 内层循环：枚举5角硬币的数量（上限为总角数除以5）
            for (five = 1; five < x * 10 / 5; five++) {
                // 检查当前组合是否满足：1角*数量 + 2角*数量*2 + 5角*数量*5 == 总角数（x*10）
                // 等式左边计算总角数，右边是目标总角数
                if (one + two * 2 + five * 5 == x * 10) {
                    // 找到一组解后，输出结果（注意：five后面缺少换行，为保持原样保留）
                    cout << "可以用" << one << "个一角加" << two << "个两角加" << five
                         << "个五角凑成" << x << "元" << endl;

                    // 使用goto直接跳出所有循环，因为只需求出一组解即可（题目未要求全部解）
                    goto out;
                }
            }
        }
    }

out:  // goto跳转标签，程序执行到这里后直接返回，结束main函数
    return 0;
}