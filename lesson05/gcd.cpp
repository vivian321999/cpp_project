#include <iostream>   // 包含输入输出流头文件，用于cin和cout
using namespace std;  // 使用标准命名空间，简化代码书写

int main() {   // 主函数，程序入口
    int a, b;  // 定义两个整数变量，用于存储用户输入的两个数
    int t;     // 定义临时变量t，用于存储余数

    cin >> a >> b;  // 从键盘读取两个整数，分别存入a和b

    int origa = a;  // 保存a的原始值，用于最后输出
    int origb = b;  // 保存b的原始值，用于最后输出

    // 欧几里得算法（辗转相除法）核心循环
    // 当b不等于0时，继续执行
    while (b != 0) {
        t = a % b;  // 计算a除以b的余数，存入t
        a = b;      // 将b的值赋给a（除数变成新的被除数）
        b = t;      // 将余数赋给b（余数变成新的除数）
    }
    // 循环结束时，b=0，a中存储的就是最大公约数

    // 输出结果：显示原始两个数和它们的最大公约数
    cout << "gcd(" << origa << "," << origb << ")=" << a << endl;

    return 0;  // 程序正常结束，返回0
}